for year in years:
    start = f'{year}-06-01'
    end = f'{year}-08-31'

    # ดึงภาพเรดาร์ Sentinel-1 (C-band Synthetic Aperture Radar)
    s1 = ee.ImageCollection('COPERNICUS/S1_GRD') \
           .filterBounds(roi) \
           .filterDate(start, end) \
           .filter(ee.Filter.eq('instrumentMode', 'IW')) \
           .filter(ee.Filter.listContains('transmitterReceiverPolarisation', 'VV')) \
           .median()

    # ใช้แบนด์ VV (Vertical-Vertical) ซึ่งสะท้อนโครงสร้างคอนกรีตได้ดีที่สุด
    vv_band = s1.select('VV')

    # หาค่าเฉลี่ยการสะท้อนกลับในพื้นที่ (หน่วยเป็น Decibels: dB)
    mean_vv = vv_band.reduceRegion(
        reducer=ee.Reducer.mean(),
        geometry=roi,
        scale=10,
        maxPixels=1e9
    ).get('VV').getInfo()

