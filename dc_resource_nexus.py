"""**การกลืนกินพื้นที่ทำกิน (Land Displacement)**"""

import ee
import pandas as pd
import matplotlib.pyplot as plt

# พิกัด Council Bluffs, IA
lat_ia, lon_ia = 41.221, -95.862
roi_ia = ee.Geometry.Point([lon_ia, lat_ia]).buffer(5000)

# ข้อมูล CDL อัปเดตสมบูรณ์สุดถึงประมาณปี 2023
years_cdl = [2020, 2021, 2022, 2023]

crop_results = []
print("กำลังคำนวณพื้นที่เกษตรกรรม (Hectares) ที่สูญหายไปจากการขยายตัวของตึก")

for year in years_cdl:
    # ใช้ฐานข้อมูล USDA Cropland Data Layer
    cdl = ee.Image(f'USDA/NASS/CDL/{year}').select('cropland').clip(roi_ia)

    # รหัส 1-60 คือพื้นที่เพาะปลูกพืชเศรษฐกิจ
    is_crop = cdl.lte(60).And(cdl.gte(1))

    # คำนวณพื้นที่ (แปลงจากตารางเมตร เป็น เฮกตาร์)
    area_image = is_crop.multiply(ee.Image.pixelArea())
    crop_area_dict = area_image.reduceRegion(
        reducer=ee.Reducer.sum(),
        geometry=roi_ia,
        scale=30,
        maxPixels=1e9
    ).getInfo()

    crop_hectares = crop_area_dict.get('cropland') / 10000 if crop_area_dict.get('cropland') else 0

    crop_results.append({
        'Year': year,
        'Active Farmland (Hectares)': round(crop_hectares, 2)
    })

df_crop_loss = pd.DataFrame(crop_results)

# พล็อตกราฟพื้นที่เกษตรที่หายไป
plt.figure(figsize=(9, 5))
color_loss = '#d35400'

plt.plot(df_crop_loss['Year'], df_crop_loss['Active Farmland (Hectares)'], marker='s', color=color_loss, linewidth=4, markersize=10, label='Active Farmland Area')
