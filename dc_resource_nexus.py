"""**การหดตัวของแหล่งน้ำ**"""

import ee
import pandas as pd
import matplotlib.pyplot as plt

# 1. กำหนดพิกัดพื้นที่ Mesa, Arizona และรัศมี 5 กม.
lat, lon = 33.324, -111.602
roi = ee.Geometry.Point([lon, lat]).buffer(5000)
years = [2020, 2021, 2022, 2023, 2024, 2025]

water_results = []
print("กำลังใช้ดาวเทียม Sentinel-2 คำนวณพื้นที่การหดตัวของแหล่งน้ำปี 2020-2025")

# 2. วนลูปดึงข้อมูลรายปี
for year in years:
    start = f'{year}-06-01'
    end = f'{year}-08-31'

    # ดึงภาพ Sentinel-2 คัดกรองภาพที่เมฆน้อยกว่า 15%
    s2 = ee.ImageCollection("COPERNICUS/S2_SR_HARMONIZED") \
           .filterBounds(roi) \
           .filterDate(start, end) \
           .filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE', 15)) \
           .median()

    # คำนวณ NDWI
    ndwi = s2.normalizedDifference(['B3', 'B8'])

    # ตั้งเกณฑ์ (Threshold) พิกเซลที่เป็นน้ำ (ค่า NDWI > 0.0)
    water_mask = ndwi.gt(0.0)

    # คำนวณพื้นที่ผิวน้ำรวม และ "ล็อกชื่อแบนด์" เป็น 'water_area' เพื่อป้องกัน GEE เปลี่ยนชื่อ
    water_area_img = water_mask.multiply(ee.Image.pixelArea()).rename('water_area')

    # รวมพื้นที่พิกเซลทั้งหมดในเขต ROI โดยเรียกใช้ชื่อคีย์ที่ตั้งไว้
    total_water_pixels = water_area_img.reduceRegion(
        reducer=ee.Reducer.sum(),
        geometry=roi,
        scale=10,
        maxPixels=1e9
    ).get('water_area')

    area_meters = total_water_pixels.getInfo()

    # แปลงหน่วยจากตารางเมตร เป็น เฮกตาร์ (Hectares)
    area_hectares = round(area_meters / 10000, 2) if area_meters else 0

    water_results.append({
        'Year': year,
        'Water Area (Hectares)': area_hectares
    })
    print(f"คำนวณพื้นที่น้ำปี {year} สำเร็จ")

# 3. แปลงข้อมูลเป็น DataFrame
df_water = pd.DataFrame(water_results)

# 4. พล็อตกราฟเส้นแสดงแนวโน้มการหดตัวของแหล่งน้ำ
plt.figure(figsize=(10, 5))
plt.plot(df_water['Year'], df_water['Water Area (Hectares)'], marker='s', color='#1bc4d9', linewidth=2.5, label='Surface Water Area')

plt.title('Multi-Year Surface Water Shrinkage Trend (2020-2025) - Mesa, AZ', fontsize=13, fontweight='bold')
plt.xlabel('Year', fontsize=11)
plt.ylabel('Water Area (Hectares)', fontsize=11)
plt.xticks(years)
plt.grid(True, linestyle='--', alpha=0.5)
plt.legend(loc='upper right')
plt.tight_layout()

