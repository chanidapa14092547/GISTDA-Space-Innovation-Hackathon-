# ฟังก์ชันคำนวณบน GEE Server (ลดโอกาส Error จากภาพว่างเปล่า)
def calc_lst(img):
    return img.select('ST_B10').multiply(0.00341802).add(149.0).subtract(273.15).rename('LST_C')

def calc_s2(img):
    ndwi = img.normalizedDifference(['B3', 'B8']).rename('NDWI')
    ndvi = img.normalizedDifference(['B8', 'B4']).rename('NDVI')
    ndbi = img.normalizedDifference(['B11', 'B8']).rename('NDBI')
    return img.addBands([ndwi, ndvi, ndbi])

# 2. วนลูปดึงข้อมูล
for name, coords in dc_locations.items():
    print(f" กำลังสแกนพื้นที่: {name}")
    roi = ee.Geometry.Point([coords['lon'], coords['lat']]).buffer(5000)

    for dt in months:
        year_month = dt.strftime('%Y-%m')

        # ขยายกรอบเวลาค้นหาภาพเป็น 3 เดือน ป้องกันเมฆบังหมด
        start_str = (dt - pd.DateOffset(months=1)).strftime('%Y-%m-%d')
        end_str = (dt + pd.DateOffset(months=1)).strftime('%Y-%m-%d')
        exact_month_start = dt.strftime('%Y-%m-%d')
        exact_month_end = (dt + pd.DateOffset(months=1)).strftime('%Y-%m-%d')

        try:
            # LST
            l8 = ee.ImageCollection("LANDSAT/LC08/C02/T1_L2").filterBounds(roi).filterDate(start_str, end_str).map(calc_lst).median()
            lst_val = l8.reduceRegion(ee.Reducer.mean(), roi, 100).get('LST_C').getInfo()

            # NDWI, NDVI, NDBI
            s2 = ee.ImageCollection("COPERNICUS/S2_HARMONIZED").filterBounds(roi).filterDate(start_str, end_str).map(calc_s2).median()
            s2_res = s2.reduceRegion(ee.Reducer.mean(), roi, 100).getInfo() or {}

            # Precipitation & Soil Moisture
            era5 = ee.ImageCollection("ECMWF/ERA5_LAND/MONTHLY_AGGR").filterBounds(roi).filterDate(exact_month_start, exact_month_end).median()
            era5_res = era5.reduceRegion(ee.Reducer.mean(), roi, 11000).getInfo() or {}

            precip_val = era5_res.get('total_precipitation')
            if precip_val is not None: precip_val *= 1000

            # บันทึกข้อมูลที่ดึงมาใช้งานได้
            dashboard_data.append({
                'data_center_name': name, 'latitude': coords['lat'], 'longitude': coords['lon'], 'year_month': year_month,
                'mean_LST_C': lst_val, 'mean_NDWI': s2_res.get('NDWI'), 'mean_NDVI': s2_res.get('NDVI'),
                'mean_NDBI': s2_res.get('NDBI'), 'precipitation_mm': precip_val, 'soil_moisture': era5_res.get('volumetric_soil_water_layer_1')
            })
        except Exception as e:
            # ถ้าระบบ GEE ล่มในเดือนนั้น ให้บันทึก NaN (ค่าว่าง) แทน เพื่อรักษาโครงสร้างตารางเอาไว้
            dashboard_data.append({
                'data_center_name': name, 'latitude': coords['lat'], 'longitude': coords['lon'], 'year_month': year_month,
                'mean_LST_C': np.nan, 'mean_NDWI': np.nan, 'mean_NDVI': np.nan, 'mean_NDBI': np.nan,
                'precipitation_mm': np.nan, 'soil_moisture': np.nan
            })

df = pd.DataFrame(dashboard_data)


print(" ดาวน์โหลดเสร็จสิ้น กำลังแก้ไขข้อมูลแหว่งและคำนวณดัชนี")

# เรียงลำดับข้อมูล
df.sort_values(by=['data_center_name', 'year_month'], inplace=True)

# เติมข้อมูลที่ขาดหาย (Interpolate)
cols_to_fill = ['mean_LST_C', 'mean_NDWI', 'mean_NDVI', 'mean_NDBI', 'precipitation_mm', 'soil_moisture']
df[cols_to_fill] = df.groupby('data_center_name')[cols_to_fill].transform(lambda x: x.interpolate(method='linear', limit_direction='both'))

# คำนวณความเปลี่ยนแปลง 1 ปี (1Y Change)
df['lst_change_1y'] = df.groupby('data_center_name')['mean_LST_C'].diff(periods=12).fillna(0)
df['ndwi_change_1y'] = df.groupby('data_center_name')['mean_NDWI'].diff(periods=12).fillna(0)
df['ndvi_change_1y'] = df.groupby('data_center_name')['mean_NDVI'].diff(periods=12).fillna(0)
df['ndbi_change_1y'] = df.groupby('data_center_name')['mean_NDBI'].diff(periods=12).fillna(0)

# ฟังก์ชัน Normalize
def norm_bad_if_high(s):
    diff = s.max() - s.min()
    return ((s - s.min()) / diff * 100) if diff != 0 else pd.Series(50, index=s.index)

def norm_bad_if_low(s):
    diff = s.max() - s.min()
    return ((s.max() - s) / diff * 100) if diff != 0 else pd.Series(50, index=s.index)

#  ECI Score
df['ECI_score'] = (
    norm_bad_if_high(df['lst_change_1y']) * 0.3 +
    norm_bad_if_high(df['ndbi_change_1y']) * 0.3 +
    norm_bad_if_low(df['ndwi_change_1y']) * 0.2 +
    norm_bad_if_low(df['ndvi_change_1y']) * 0.2
).round(2)

#  ESS Score
df['ESS_score'] = (
    norm_bad_if_high(df['mean_LST_C']) * 0.3 +
    norm_bad_if_high(df['mean_NDBI']) * 0.3 +
    norm_bad_if_low(df['mean_NDWI']) * 0.2 +
    norm_bad_if_low(df['soil_moisture']) * 0.2
).round(2)

#  Risk Score
df['risk_score'] = ((df['ECI_score'] + df['ESS_score']) / 2).round(2)

def get_risk_level(score):
    if score >= 75: return 'Critical'
    elif score >= 50: return 'Concern'
    elif score >= 25: return 'Watch'
    else: return 'Stable'

df['risk_level'] = df['risk_score'].apply(get_risk_level)

# พยากรณ์ความเสี่ยงล่วงหน้า (AI Trend Forecasting)
df['risk_trend_monthly'] = df.groupby('data_center_name')['risk_score'].diff(periods=12).fillna(0) / 12
df['forecast_risk_score_6m'] = (df['risk_score'] + (df['risk_trend_monthly'] * 6)).clip(0, 100).round(2)
df['forecast_risk_level_6m'] = df['forecast_risk_score_6m'].apply(get_risk_level)
df['forecast_risk_score_12m'] = (df['risk_score'] + (df['risk_trend_monthly'] * 12)).clip(0, 100).round(2)
df['forecast_risk_level_12m'] = df['forecast_risk_score_12m'].apply(get_risk_level)


final_columns = [
    'data_center_name', 'latitude', 'longitude', 'year_month',
    'mean_LST_C', 'mean_NDWI', 'mean_NDVI', 'mean_NDBI',
    'precipitation_mm', 'soil_moisture',
    'lst_change_1y', 'ndwi_change_1y', 'ndvi_change_1y', 'ndbi_change_1y',
    'ECI_score', 'ESS_score',
    'risk_score', 'risk_level',
    'forecast_risk_score_6m', 'forecast_risk_level_6m',
    'forecast_risk_score_12m', 'forecast_risk_level_12m'
]

df_final = df[final_columns].copy()

#เติมค่าว่างทั้งหมด (ถ้ายังมีหลงเหลือ) ให้เป็น 0
df_final.fillna(0, inplace=True)

