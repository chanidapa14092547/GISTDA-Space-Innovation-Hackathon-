roi = ee.Geometry.Point([-111.602, 33.324]).buffer(5000)
years = [2020, 2021, 2022, 2023, 2024, 2025]
data_list = []

print("กำลังประมวลผลโมเดล Causal Inference (SAR vs Soil Moisture)")

for year in years:
    start, end = f'{year}-06-01', f'{year}-08-31'

    # ดึงข้อมูล Sentinel-1 (SAR) เพื่อจับตาการขยายตัวของตึก
    s1 = ee.ImageCollection('COPERNICUS/S1_GRD') \
            .filterBounds(roi) \
            .filterDate(start, end) \
            .filter(ee.Filter.eq('instrumentMode', 'IW')) \
            .select('VV') \
            .median()

    sar_val = s1.reduceRegion(ee.Reducer.mean(), roi, 100).get('VV').getInfo()

    # ดึงข้อมูล ERA5 (Soil Moisture) วัดระดับความชื้นในหน้าดิน
    era = ee.ImageCollection("ECMWF/ERA5_LAND/MONTHLY_AGGR") \
            .filterBounds(roi) \
            .filterDate(start, end) \
            .median()
    sm_val = era.select('volumetric_soil_water_layer_1').reduceRegion(ee.Reducer.mean(), roi, 11000).get('volumetric_soil_water_layer_1').getInfo()

    data_list.append({
        'Year': year,
        'Infrastructure (SAR dB)': sar_val,
        'Soil Moisture (m3/m3)': sm_val
    })

df_causal = pd.DataFrame(data_list)
